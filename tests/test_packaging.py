"""REL-06: the sdist and the wheel hold only an approved allow-list of files.

The sdist used to take whatever was on disk and not in ``.gitignore``. Hatch does not
read ``.git/info/exclude``, so a developer working copy leaked ``.claude/`` (local tool
settings, a whole stale worktree) and ``.playwright-mcp/`` browser logs into it
(release-readiness H-5). These tests build both archives offline with the locked
hatchling from a controlled copy of the git-tracked files, seeded with synthetic
canary files in the places that leaked, and check every archive member against an
explicit manifest.

Nothing real is archived: the build tree holds only tracked files plus canaries whose
content is a fixed marker string, and failure messages print member names only.
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
import tarfile
import tomllib
import zipfile
from pathlib import Path, PurePosixPath

import pytest

ROOT = Path(__file__).parent.parent
PYPROJECT = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))
NAME = PYPROJECT["project"]["name"]
VERSION = PYPROJECT["project"]["version"]
DIST = NAME.replace("-", "_")
PACKAGE_DIR = "src/qradar_soar_mcp"

# The approved sdist content outside the package: build config, readme (project
# metadata) and the licence. PKG-INFO is generated by the backend, and hatchling
# always adds the root .gitignore (SdistBuilder.get_default_build_data) so a wheel
# built from the sdist applies the same ignore rules; it is a tracked, public file.
SDIST_TOP_LEVEL = frozenset({"pyproject.toml", "README.md", "LICENSE", "PKG-INFO", ".gitignore"})
WHEEL_DIST_INFO = frozenset({"METADATA", "WHEEL", "RECORD", "entry_points.txt", "licenses/LICENSE"})
CANARY_TEXT = "REL-06 packaging canary: this file must never appear in an archive.\n"

# Where local-only material lived on the machine that showed H-5, plus the other
# classes of file the allow-list must keep out. Every path is relative to the root.
CANARIES = (
    ".claude/settings.local.json",
    ".claude/worktrees/stale-branch/pyproject.toml",
    ".claude/worktrees/stale-branch/src/qradar_soar_mcp/canary.py",
    ".claude/worktrees/stale-branch/.github/workflows/canary.yml",
    ".playwright-mcp/console-canary.log",
    ".playwright-mcp/page-canary.yml",
    ".playwright-mcp/page-canary.png",
    ".git/config",
    ".git/info/exclude",
    ".env",
    ".env.local",
    ".venv/pyvenv.cfg",
    "credentials/canary-credentials.json",
    "screenshots/canary.png",
    "browser-canary.log",
    "audit.jsonl",
    "dist/stale-canary.tar.gz",
    "scripts/probe/raw/canary.json",
    "tests/fixtures/raw/canary.json",
    f"{PACKAGE_DIR}/__pycache__/canary.cpython-312.pyc",
    f"{PACKAGE_DIR}/canary.log",
    f"{PACKAGE_DIR}/canary.pem",
)

# A member whose path contains any of these components is rejected outright.
FORBIDDEN_COMPONENTS = frozenset(
    {
        ".claude",
        ".playwright-mcp",
        ".git",
        ".github",
        ".venv",
        "__pycache__",
        "worktrees",
        "automation",
        "tests",
        "docs",
        "scripts",
        "credentials",
        "screenshots",
    }
)
FORBIDDEN_SUFFIXES = (".log", ".png", ".pem", ".key", ".pyc", ".jsonl", ".env")


def _tracked_files() -> list[str]:
    out = subprocess.run(
        ["git", "ls-files", "-z"], cwd=ROOT, check=True, capture_output=True, text=True
    ).stdout
    return [p for p in out.split("\0") if p and (ROOT / p).is_file()]


TRACKED = _tracked_files()
PACKAGE_FILES = frozenset(p for p in TRACKED if p.startswith(PACKAGE_DIR + "/"))


def _hatchling_build(target: str, root: Path, out: Path) -> Path:
    env = {k: v for k, v in os.environ.items() if not k.startswith(("SOAR_", "HATCH_"))}
    proc = subprocess.run(
        [sys.executable, "-m", "hatchling", "build", "-t", target, "-d", str(out)],
        cwd=root,
        env=env,
        capture_output=True,
        text=True,
        check=False,
    )
    assert proc.returncode == 0, f"hatchling {target} build failed:\n{proc.stderr[-2000:]}"
    pattern = f"{DIST}-{VERSION}.tar.gz" if target == "sdist" else f"{DIST}-{VERSION}-*.whl"
    built = sorted(out.glob(pattern))
    assert len(built) == 1, [p.name for p in out.iterdir()]
    return built[0]


@pytest.fixture(scope="module")
def build_tree(tmp_path_factory: pytest.TempPathFactory) -> Path:
    """A copy of the tracked files plus canaries, outside the real working tree."""
    tree = tmp_path_factory.mktemp("rel06") / "checkout"
    for rel in TRACKED:
        dest = tree / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(ROOT / rel, dest)
    for rel in CANARIES:
        dest = tree / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(CANARY_TEXT, encoding="utf-8")
    # Mirror the H-5 machine: these directories are excluded only locally.
    (tree / ".git/info/exclude").write_text(".claude/\n.playwright-mcp/\n", encoding="utf-8")
    return tree


@pytest.fixture(scope="module")
def sdist(build_tree: Path, tmp_path_factory: pytest.TempPathFactory) -> Path:
    return _hatchling_build("sdist", build_tree, tmp_path_factory.mktemp("sdist-out"))


@pytest.fixture(scope="module")
def wheel(build_tree: Path, tmp_path_factory: pytest.TempPathFactory) -> Path:
    return _hatchling_build("wheel", build_tree, tmp_path_factory.mktemp("wheel-out"))


def _sdist_members(path: Path) -> list[str]:
    """Member names relative to the sdist root, read from the index without extracting."""
    prefix = f"{DIST}-{VERSION}/"
    names: list[str] = []
    with tarfile.open(path, "r:gz") as tar:
        for member in tar.getmembers():
            assert member.isfile() or member.isdir(), f"non-regular member: {member.name}"
            pure = PurePosixPath(member.name)
            assert not pure.is_absolute() and ".." not in pure.parts, member.name
            assert member.name.startswith(prefix), member.name
            if member.isfile():
                names.append(member.name.removeprefix(prefix))
    return names


def _wheel_members(path: Path) -> list[str]:
    with zipfile.ZipFile(path) as whl:
        names = whl.namelist()
    for name in names:
        pure = PurePosixPath(name)
        assert not pure.is_absolute() and ".." not in pure.parts, name
    return names


def _assert_no_forbidden(names: list[str]) -> None:
    bad = [
        n
        for n in names
        if FORBIDDEN_COMPONENTS.intersection(PurePosixPath(n).parts)
        or n.endswith(FORBIDDEN_SUFFIXES)
        or PurePosixPath(n).name.startswith(".env")
    ]
    assert not bad, f"forbidden archive members: {sorted(bad)}"


def _expected_wheel(dist_info: str) -> set[str]:
    package = {p.removeprefix("src/") for p in PACKAGE_FILES}
    return package | {f"{dist_info}/{f}" for f in WHEEL_DIST_INFO}


# ------------------------------------------------------------ configuration


def test_sdist_config_is_an_explicit_allow_list():
    sdist_cfg = PYPROJECT["tool"]["hatch"]["build"]["targets"]["sdist"]
    assert sdist_cfg["only-include"] == [PACKAGE_DIR, "pyproject.toml", "README.md", "LICENSE"]
    assert "force-include" not in sdist_cfg
    assert "include" not in sdist_cfg
    for entry in sdist_cfg["only-include"]:
        assert not any(ch in entry for ch in "*?[!"), f"wildcard in only-include: {entry}"


def test_package_holds_only_source_and_marker():
    """Guards the package allow-list entry: only .py files and py.typed are tracked."""
    assert f"{PACKAGE_DIR}/py.typed" in PACKAGE_FILES
    odd = [p for p in PACKAGE_FILES if not (p.endswith(".py") or p.endswith("/py.typed"))]
    assert not odd, odd


# ------------------------------------------------------------ sdist


def test_sdist_matches_the_approved_manifest(sdist: Path):
    names = _sdist_members(sdist)
    assert len(names) == len(set(names)), "duplicate sdist members"
    expected = SDIST_TOP_LEVEL | PACKAGE_FILES
    assert set(names) == expected, {
        "unexpected": sorted(set(names) - expected),
        "missing": sorted(expected - set(names)),
    }


def test_sdist_rejects_canaries_and_local_material(sdist: Path):
    names = set(_sdist_members(sdist))
    leaked = sorted(c for c in CANARIES if c in names)
    assert not leaked, f"canaries leaked into the sdist: {leaked}"
    _assert_no_forbidden(sorted(names))
    # No member carries canary content either, even under an approved name.
    with tarfile.open(sdist, "r:gz") as tar:
        for member in tar.getmembers():
            if member.isfile():
                handle = tar.extractfile(member)
                assert handle is not None
                assert CANARY_TEXT.encode() not in handle.read(), member.name


def test_sdist_pkg_info_names_the_project(sdist: Path):
    with tarfile.open(sdist, "r:gz") as tar:
        handle = tar.extractfile(f"{DIST}-{VERSION}/PKG-INFO")
        assert handle is not None
        pkg_info = handle.read().decode("utf-8")
    assert f"\nName: {NAME}\n" in pkg_info
    assert f"\nVersion: {VERSION}\n" in pkg_info
    assert "\nLicense-File: LICENSE\n" in pkg_info


# ------------------------------------------------------------ wheel


def test_wheel_holds_only_the_package_and_dist_info(wheel: Path):
    names = _wheel_members(wheel)
    _assert_no_forbidden(names)
    expected = _expected_wheel(f"{DIST}-{VERSION}.dist-info")
    assert set(names) == expected, {
        "unexpected": sorted(set(names) - expected),
        "missing": sorted(expected - set(names)),
    }


# ------------------------------------------------------------ sdist -> wheel


@pytest.fixture(scope="module")
def wheel_from_sdist(sdist: Path, tmp_path_factory: pytest.TempPathFactory) -> Path:
    """Build a wheel from the sdist alone, in a directory unrelated to the checkout."""
    _sdist_members(sdist)  # validates every member before anything is written
    fresh = tmp_path_factory.mktemp("fresh")
    with tarfile.open(sdist, "r:gz") as tar:
        tar.extractall(fresh, filter="data")
    root = fresh / f"{DIST}-{VERSION}"
    assert not (root / ".git").exists()
    return _hatchling_build("wheel", root, tmp_path_factory.mktemp("wheel-from-sdist"))


def test_sdist_builds_an_equivalent_wheel(wheel_from_sdist: Path, wheel: Path):
    assert set(_wheel_members(wheel_from_sdist)) == set(_wheel_members(wheel))


def test_wheel_from_sdist_metadata_and_entry_points(wheel_from_sdist: Path):
    dist_info = f"{DIST}-{VERSION}.dist-info"
    with zipfile.ZipFile(wheel_from_sdist) as whl:
        metadata = whl.read(f"{dist_info}/METADATA").decode("utf-8")
        entry_points = whl.read(f"{dist_info}/entry_points.txt").decode("utf-8")
    assert f"\nName: {NAME}\n" in metadata
    assert f"\nVersion: {VERSION}\n" in metadata
    for script, target in PYPROJECT["project"]["scripts"].items():
        assert f"{script} = {target}" in entry_points, script
